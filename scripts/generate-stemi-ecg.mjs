#!/usr/bin/env node
// Build the default STEMI case's 12-lead ECG document and write it as the
// literal the server seeds (server/seeders/stemiV2Ecg.js).
//
// The server may not import src/ (the Docker runtime copies server/ only), so
// the document is compiled here from the ECG engine's own preset and checked
// in. tests/client/stemi-v2-ecg.test.js regenerates it and fails on drift.
//
// Changes from the stock `anterior_injury_pattern` preset, and why:
//   - lead II ST -0.10 mV (preset +0.05): the limb leads III, aVL and aVF are
//     DERIVED from I and II, so this is what gives the reciprocal inferior ST
//     depression (III -0.20, aVF -0.15) and the slight aVL elevation (+0.15)
//     of a proximal LAD occlusion. The preset's tracing had almost none.
//   - no Q waves in V2-V3 (preset -0.22 mV): 45 minutes into an infarct,
//     pathological Q waves are not yet expected; the case says so.
//
// Usage: node scripts/generate-stemi-ecg.mjs [--check]

import { writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { create_case_document } from '../src/components/ecg/caseDocument.js';
import { validate_render_spec } from '../src/components/ecg/presets.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = path.join(ROOT, 'server', 'seeders', 'stemiV2Ecg.js');

/** The default STEMI case's ECG document, from the engine's preset plus the two edits above. */
export function buildStemiEcgDocument() {
    const document = create_case_document({
        // The id reaches the learner with the manifest: it must not name the diagnosis.
        id: 'chest-pain-arrival-ecg',
        title: 'Arrival 12-lead ECG',
        preset_id: 'anterior_injury_pattern',
        purpose: 'Interpret the first 12-lead ECG of a man with ongoing chest pain, and decide what it means for the next ten minutes.',
        prompt: 'Read this tracing systematically — rate, rhythm, axis, intervals, morphology — and say what it changes about what you do next.',
        patient: {
            age_years: 55,
            sex: 'male',
            presentation: 'A 55-year-old man with 45 minutes of central chest pain. Recorded on arrival in the emergency department.',
            history: 'Hypertension, type 2 diabetes, smoker.',
            vitals: { blood_pressure: '152/94', respiratory_rate: 20, oxygen_saturation_percent: 95 },
        },
        seed: 20261004,
    });
    const recording = document.manifest.recordings[0];
    const channels = recording.render_spec.morphology.channels;
    const edited = {
        ...channels,
        II: { ...channels.II, st: -0.10 },
        V2: { ...channels.V2, q: channels.V1.q },
        V3: { ...channels.V3, q: channels.V1.q },
    };
    const render_spec = validate_render_spec({
        ...recording.render_spec,
        morphology: { ...recording.render_spec.morphology, channels: edited },
    });
    const activity = document.rubric.activities[0];
    return {
        manifest: {
            ...document.manifest,
            recordings: [{ ...recording, render_spec }],
        },
        rubric: {
            ...document.rubric,
            activities: [{
                ...activity,
                expected: {
                    ...activity.expected,
                    finding_ids: ['sinus_rhythm', 'st_elevation_anterior', 'st_depression', 'poor_r_wave_progression'],
                    critical_finding_ids: ['st_elevation_anterior'],
                },
                rationale: 'Convex ST elevation V1–V4 (maximal V2–V3) with slight elevation in aVL and reciprocal ST depression in III and aVF: an anterior injury pattern from a proximal LAD occlusion. No Q waves yet, consistent with 45 minutes of symptoms.',
                // What the on-call cardiologist may say once the learner has
                // done the work (services/specialistBrief.js reads only this).
                findings: [
                    { id: 'rate', text: 'Sinus rhythm at about 92 per minute, normal axis, PR 160 ms, QRS 90 ms.' },
                    { id: 'st_elevation', text: 'ST elevation V1 to V4, maximal in V2 and V3 (about 3 mm), with slight elevation in aVL.' },
                    { id: 'reciprocal', text: 'Reciprocal ST depression in III and aVF.' },
                    { id: 'q_waves', text: 'No pathological Q waves yet; early loss of R-wave height in V1 and V2.' },
                ],
            }],
        },
    };
}

function render(document) {
    return `// GENERATED by scripts/generate-stemi-ecg.mjs — do not edit by hand.\n`
        + `// The default STEMI case's arrival ECG (config.ecg). Regenerate with:\n`
        + `//   node scripts/generate-stemi-ecg.mjs\n\n`
        + `export const STEMI_V2_ECG = ${JSON.stringify(document, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const text = render(buildStemiEcgDocument());
    if (process.argv.includes('--check')) {
        const current = readFileSync(OUTPUT, 'utf8');
        if (current !== text) {
            process.stderr.write(`${OUTPUT} is stale — run node scripts/generate-stemi-ecg.mjs\n`);
            process.exit(1);
        }
        process.stdout.write('stemiV2Ecg.js is current\n');
    } else {
        writeFileSync(OUTPUT, text);
        process.stdout.write(`${OUTPUT}  ${text.length} bytes\n`);
    }
}

export { render as renderStemiEcgModule };
