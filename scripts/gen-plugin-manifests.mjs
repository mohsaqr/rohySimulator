#!/usr/bin/env node
/**
 * Freeze every plugin manifest into server/shared/plugins/ so the SERVER can
 * read a plugin's vocabulary without importing from src/.
 *
 * Why generate instead of hand-mirroring: rohy already duplicates the password
 * policy across the client/server boundary and pins it with a test, because
 * the client cannot import server/routes/_helpers.js. This is the same
 * boundary in the other direction — server/ is copied into the Docker runtime
 * stage and src/ is not — but a plugin's verb list is far larger than a
 * password rule, so it is generated and drift-checked (the `docs:check`
 * pattern) rather than mirrored by hand.
 *
 * Run: npm run plugins:gen     Check: npm run plugins:check
 */
import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { validateManifest, assertShippedManifest, canonicalManifest } from '../server/shared/pluginRegistry.js';
// Loading the registry registers rohy's core verb names with pluginRegistry,
// which validateManifest needs to check a manifest's `vocabulary.coreVerbs`.
// (learningVerbs folds the PREVIOUS generated manifests; that is fine — the
// fresh ones are validated individually below.)
import '../server/shared/learningVerbs.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const PLUGIN_DIR = path.join(ROOT, 'src', 'plugins');
const OUT_DIR = path.join(ROOT, 'server', 'shared', 'plugins');

/** Stable key order, so a regenerated file is byte-identical or genuinely different.
 *  The same canonicaliser the runtime drift guard uses, so the two cannot disagree. */
const sortDeep = canonicalManifest;

async function collect() {
    const ids = readdirSync(PLUGIN_DIR, { withFileTypes: true })
        // BOTH files, matching the runtime's own predicate. The generator used
        // to key off manifest.js alone while runtime discovery globs
        // index.jsx — so a manifest-only folder became a server whitelist and
        // navigation entry with no component to mount, and an index-only
        // folder mounted client-side while its events were rejected by the
        // server. Two registries with different membership rules is one
        // registry too many.
        .filter((e) => e.isDirectory()
            && existsSync(path.join(PLUGIN_DIR, e.name, 'manifest.js'))
            && existsSync(path.join(PLUGIN_DIR, e.name, 'index.jsx')))
        .map((e) => e.name)
        .sort();

    return Promise.all(ids.map(async (id) => {
        const mod = await import(pathToFileURL(path.join(PLUGIN_DIR, id, 'manifest.js')).href);
        // Valid, AND fit to ship (R33/R34 — see assertShippedManifest).
        const manifest = assertShippedManifest(validateManifest(mod.manifest ?? mod.default));
        if (manifest.id !== id) {
            throw new Error(`src/plugins/${id}/ declares id '${manifest.id}' — the directory name is the id`);
        }
        return manifest;
    }));
}

function render(manifests) {
    const body = manifests.map((m) => JSON.stringify(sortDeep(m), null, 4)).join(',\n');
    return `// GENERATED by scripts/gen-plugin-manifests.mjs — do not edit.
// Source of truth: src/plugins/<id>/manifest.js
// Regenerate: npm run plugins:gen
export const PLUGIN_MANIFESTS = [
${body.split('\n').map((l) => (l ? `    ${l}` : l)).join('\n')}
];

export default PLUGIN_MANIFESTS;
`;
}

const manifests = await collect();
const outFile = path.join(OUT_DIR, 'manifests.generated.js');
const next = render(manifests);
const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;

if (process.argv.includes('--check')) {
    if (prev !== next) {
        console.error('Plugin manifest drift: server/shared/plugins/manifests.generated.js is stale.');
        console.error('Run `npm run plugins:gen` and commit the result.');
        process.exit(1);
    }
    console.log(`plugins:check OK — ${manifests.length} manifest(s) in sync`);
} else {
    writeFileSync(outFile, next);
    console.log(`Wrote ${manifests.length} manifest(s): ${manifests.map((m) => m.id).join(', ')}`);
}
